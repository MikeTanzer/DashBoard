export function PlatformLogo({
  platform,
  height = 14,
}: {
  platform: string;
  height?: number;
}) {
  const logo = LOGOS[platform];
  if (!logo) return null;

  const h = height * logo.scale;

  return (
    <svg
      height={h}
      width={h * logo.aspect}
      viewBox={logo.viewBox}
      fill="currentColor"
      role="img"
      aria-label={logo.label}
      style={{ display: "block", flexShrink: 0 }}
    >
      {logo.body}
    </svg>
  );
}

/** True when we hold a real wordmark, so callers can skip the text label. */
export function hasPlatformLogo(platform: string): boolean {
  return platform in LOGOS;
}
